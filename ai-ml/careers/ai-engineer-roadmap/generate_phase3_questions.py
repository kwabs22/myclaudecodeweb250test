def build():
    questions = []
    qid = 1
    for topic, rows in TOPICS.items():
        for sub, diff, q, good, bad, expl, hint in rows:
            assert len(bad) == 3, q
            questions.append({
                "id": qid, "topic": topic, "subtopic": sub, "difficulty": diff, "type": "multiple_choice",
                "question": q, "options": [good] + bad, "correct_answer": 0, "explanation": expl, "hints": [hint],
            })
            qid += 1
    return questions


if __name__ == "__main__":
    qs = build()
    topics = {}
    for q in qs:
        topics[q["topic"]] = topics.get(q["topic"], 0) + 1
    levels = {}
    for q in qs:
        levels[q["difficulty"]] = levels.get(q["difficulty"], 0) + 1
    meta = {
        "title": "AI Engineer Roadmap - Phase 3: Generative AI Question Bank",
        "version": "1.0.0",
        "total_questions": len(qs),
        "created": "2026-10-27",
        "description": "Hand-written questions on the OpenAI API, Hugging Face, embeddings and vector databases, RAG, and agents with LangChain and LangGraph",
        "topics": topics,
        "difficulty_levels": ["beginner", "intermediate", "advanced"],
        "difficulty_counts": levels,
        "question_types": ["multiple_choice"],
    }
    with open("phase3-question-bank.json", "w", encoding="utf-8") as f:
        json.dump({"metadata": meta, "questions": qs}, f, ensure_ascii=False, indent=2)
    print(len(qs), "questions", topics, levels)
